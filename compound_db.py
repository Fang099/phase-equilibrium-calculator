"""
compound_db.py -- the built-in compound database.

data/compounds.json holds pure-component constants and binary parameters for
a small set of common liquids. It is generated by scripts/build_compound_db.py
from published tables (see that script for the sources), so it can be
extended by adding rows to data/compound_list.csv and re-running the script.

In an input file, the line

    database = builtin

fills in whatever the input does not give itself: Tc, Pc, omega, molar mass
and Antoine constants for each component, the Peng-Robinson k_ij when
model = PR, and NRTL parameters when activity = nrtl. Values typed in the
input always take precedence.
"""

import json
import os

R = 8.314462618
_DB = None


def _path():
    here = os.path.dirname(os.path.abspath(__file__))
    return os.path.join(here, "data", "compounds.json")


def load(path=None):
    """Return the database as a dict (cached)."""
    global _DB
    if _DB is None or path:
        with open(path or _path(), encoding="utf-8") as f:
            db = json.load(f)
        db["_index"] = {}
        for c in db["compounds"]:
            for key in (c["id"], c["name"], c["cas"]):
                db["_index"][_norm(key)] = c
        db["_pairs"] = {frozenset((p["a"], p["b"])): p for p in db["pairs"]}
        if path:
            return db
        _DB = db
    return _DB


def _norm(name):
    return str(name).strip().lower().replace(" ", "-").replace("_", "-")


def find(name):
    """Compound record by id, name or CAS number (case-insensitive), or None."""
    return load()["_index"].get(_norm(name))


def pair(a, b):
    """Binary parameters for compounds a and b, oriented as (a, b).
    Returns a dict that may contain:
        'dg_ab', 'dg_ba'  NRTL energies in J/mol (tau_ab = dg_ab / RT)
        'alpha'           NRTL non-randomness
        'kij_pr'          Peng-Robinson binary interaction parameter
        'nrtl_source', 'kij_source'
    """
    ra, rb = find(a), find(b)
    if ra is None or rb is None:
        return {}
    rec = load()["_pairs"].get(frozenset((ra["id"], rb["id"])))
    if rec is None:
        return {}
    out = {}
    if "nrtl" in rec:
        n = rec["nrtl"]
        b_ab, b_ba = (n["b_ab"], n["b_ba"]) if rec["a"] == ra["id"] else (n["b_ba"], n["b_ab"])
        out.update(dg_ab=b_ab * R, dg_ba=b_ba * R, alpha=n["alpha"], nrtl_source=n["source"])
    if "kij_pr" in rec:
        out.update(kij_pr=rec["kij_pr"]["value"], kij_source=rec["kij_pr"]["source"])
    return out


def sources():
    return load()["meta"]["sources"]


def apply_to_inputs(inp):
    """Fill missing properties of a parsed input (input_checker.Inputs) from
    the database. Returns (notes, warnings) describing what was used."""
    notes, warnings = [], []
    recs = {}
    for c in inp.components:
        rec = find(c)
        if rec is None:
            warnings.append(f"{c} is not in the built-in database; give its "
                            f"properties in the input")
            continue
        recs[c] = rec
        p, used = inp.props[c], []
        for key in ("Tc", "Pc", "omega"):
            if key not in p:
                p[key] = rec[key]["value"]
                used.append(key)
        if "M" not in p:
            p["M"] = rec["M"]["value"] / 1000.0          # kg/mol
            used.append("M")
        has_psat = ("antoine" in p or "Psat" in p or ("Tb" in p and "dHvap" in p))
        if not has_psat and not p.get("nonvolatile"):
            a = rec["antoine"]
            p["antoine"] = dict(A=a["A"], B=a["B"], C=a["C"], P_unit=a["P_unit"],
                                T_unit=a["T_unit"], base="log10")
            p["antoine_range"] = [a["Tmin"], a["Tmax"]]
            used.append("Antoine constants")
        if used:
            notes.append(f"{c}: {', '.join(used)}")

    names = [c for c in inp.components if c in recs]
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            pr = pair(a, b)
            key = frozenset((a, b))
            if inp.model == "PR" and "kij_pr" in pr and "kij" not in inp.pairs.get(key, {}):
                inp.pairs.setdefault(key, {})["kij"] = pr["kij_pr"]
                notes.append(f"kij({a}, {b}) = {pr['kij_pr']:g} for Peng-Robinson")
            if inp.activity == "nrtl" and "dg_ab" in pr:
                used = []
                for (i_, j_), val in (((a, b), pr["dg_ab"]), ((b, a), pr["dg_ba"])):
                    if "dg" not in inp.opairs.get((i_, j_), {}):
                        inp.opairs.setdefault((i_, j_), {})["dg"] = val
                        used.append(f"dg({i_}, {j_}) = {val:.1f} J/mol")
                if "alpha" not in inp.pairs.get(key, {}):
                    inp.pairs.setdefault(key, {})["alpha"] = pr["alpha"]
                    used.append(f"alpha = {pr['alpha']:g}")
                if used:
                    notes.append("NRTL: " + ", ".join(used))
    return notes, warnings
