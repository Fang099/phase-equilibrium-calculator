def load_edition():
    with open(os.path.join(ROOT, "site", "edition.json"), encoding="utf-8") as fh:
        cfg = json.load(fh)
    name = cfg["active"]
    for a in sys.argv[1:]:
        if a.startswith("--edition="):
            name = a.split("=", 1)[1]
    if name not in cfg["editions"]:
        sys.exit(f"unknown edition {name!r}; choose from {sorted(cfg['editions'])}")
    ed = dict(cfg["editions"][name])
    ed["name"] = name
    return ed


