def offered(kind, value):
    """Whether the edition offers this model / compound / gallery image."""
    return kind not in ED or value in ED[kind]


def apply_edition(src):
    """Keep the text marked for this edition, drop the other, fill {{act}}."""
    keep, drop = ("full", "reduced") if FULL else ("reduced", "full")
    # markers on lines of their own enclose whole lines; otherwise they are inline
    src = re.sub(rf"(?ms)^[ \t]*<!--{drop}-->[ \t]*\n.*?^[ \t]*<!--/{drop}-->[ \t]*\n", "", src)
    src = re.sub(rf"(?s)<!--{drop}-->.*?<!--/{drop}-->", "", src)
    src = re.sub(rf"(?m)^[ \t]*<!--/?{keep}-->[ \t]*\n", "", src)
    src = re.sub(rf"<!--/?{keep}-->", "", src)
    for k, v in ED["vars"].items():
        src = src.replace("{{" + k + "}}", v)
    return src


def write_edition_js():
    """What the calculator page may offer, read by assets/app.js."""
    keys = ("models", "compounds", "presets", "x_axes", "y_axes", "default", "vars")
    cfg = {k: ED[k] for k in keys if k in ED}
    with open(os.path.join(ROOT, "docs", "assets", "edition.js"), "w", encoding="utf-8") as fh:
        fh.write("/* generated by scripts/build_site.py -- do not edit */\nwindow.PEC_EDITION="
                 + json.dumps(cfg, ensure_ascii=False, separators=(",", ":")) + ";\n")


def asset_version():
    h = hashlib.sha1()
    for folder in ("docs/assets", "docs/py", "site"):
        for base, _dirs, files in sorted(os.walk(os.path.join(ROOT, folder))):
            if "vendor" in base:
                continue
            for f in sorted(files):
                with open(os.path.join(base, f), "rb") as fh:
                    h.update(fh.read())
    return h.hexdigest()[:10]


# --------------------------------------------------------------------------
# Code excerpts on the pages: <!--code file="x.py" def="Class.method"
# [from="text"] [to="text"]--> is replaced by that part of the current
# source, highlighted and with its real line numbers, so the excerpts can
# never drift from the code.
# --------------------------------------------------------------------------
import ast        # noqa: E402
import html       # noqa: E402
import io         # noqa: E402
import keyword    # noqa: E402
import textwrap   # noqa: E402
import tokenize   # noqa: E402


def _find_def(tree, qualname):
    node = tree
    for part in qualname.split("."):
        node = next((c for c in ast.iter_child_nodes(node)
                     if isinstance(c, (ast.FunctionDef, ast.ClassDef)) and c.name == part), None)
        if node is None:
            raise SystemExit(f"code excerpt: no definition {qualname!r}")
    return node.lineno, node.end_lineno


def _highlight(code):
    """Python source -> list of HTML lines with token classes."""
    lines = code.split("\n")
    starts = [0]
    for ln in lines:
        starts.append(starts[-1] + len(ln) + 1)
    off = lambda rc: starts[rc[0] - 1] + rc[1]
    out, pos, prev = [], 0, None
    try:
        toks = list(tokenize.generate_tokens(io.StringIO(code + "\n").readline))
    except (tokenize.TokenError, IndentationError, SyntaxError):
        toks = []
    for t in toks:
        a, b = off(t.start), off(t.end) if t.end[0] <= len(lines) else len(code)
        if a < pos or a > len(code):
            continue
        cls = None
        if t.type == tokenize.COMMENT:
            cls = "c"
        elif t.type == tokenize.STRING or tokenize.tok_name.get(t.type, "").startswith("FSTRING"):
            cls = "s"
        elif t.type == tokenize.NUMBER:
            cls = "n"
        elif t.type == tokenize.NAME:
            if keyword.iskeyword(t.string):
                cls = "k"
            elif prev in ("def", "class"):
                cls = "f"
            elif t.string == "self":
                cls = "v"
        if t.type == tokenize.NAME:
            prev = t.string
        elif t.type == tokenize.OP:
            prev = None
        out.append((None, code[pos:a]))
        out.append((cls, code[a:b]))
        pos = b
    out.append((None, code[pos:]))
    html_lines, cur = [], ""
    for cls, text in out:
        for k, piece in enumerate(text.split("\n")):
            if k:
                html_lines.append(cur)
                cur = ""
            if piece:
                e = html.escape(piece, quote=False)
                cur += f'<span class="t{cls}">{e}</span>' if cls else e
    html_lines.append(cur)
    return html_lines[:len(lines)]


def code_excerpt(m):
    at = {k: html.unescape(v) for k, v in re.findall(r'(\w+)="(.*?)"', m.group(1))}
    path = at["file"]
    with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
        src = fh.read()
    lines = src.split("\n")
    first, last = _find_def(ast.parse(src), at["def"])
    while first > 1 and lines[first - 2].lstrip().startswith("@"):
        first -= 1
    if "from" in at:
        first = next((k for k in range(first, last + 1) if at["from"] in lines[k - 1]), None)
        if first is None:
            raise SystemExit(f"code excerpt: {at['from']!r} not in {at['def']}")
    if "to" in at:
        last = next((k for k in range(first, last + 1) if at["to"] in lines[k - 1]), None)
        if last is None:
            raise SystemExit(f"code excerpt: {at['to']!r} not in {at['def']}")
    code = textwrap.dedent("\n".join(lines[first - 1:last])).rstrip()
    body = "\n".join(f'<span class="ln" data-n="{first + k}"></span>{h}'
                     for k, h in enumerate(_highlight(code)))
    url = f"{REPO_URL}/blob/main/{path}#L{first}-L{last}"
    label = html.escape(at.get("title", at["def"]))
    return (f'<figure class="code"><figcaption><span class="code-name">{label}</span>'
            f'<a href="{url}"><code>{path}</code>, lines {first}–{last}</a></figcaption>'
            f'<pre><code>{body}</code></pre></figure>')


def render_pages():
    """site/pages/*.html + site/layout.html -> docs/*.html.

    Each page starts with a comment holding its settings as JSON, e.g.
        <!-- {"title": "Concepts", "description": "...", "math": true, "data": true} -->
    Text after a line containing only <!-- scripts --> is placed after the
    shared scripts, so page scripts can use the chart library."""
    with open(os.path.join(ROOT, "site", "layout.html"), encoding="utf-8") as fh:
        layout = apply_edition(fh.read())
    write_edition_js()
    version = asset_version()
    pages_dir = os.path.join(ROOT, "site", "pages")
    for fn in sorted(os.listdir(pages_dir)):
        if not fn.endswith(".html"):
            continue
        with open(os.path.join(pages_dir, fn), encoding="utf-8") as fh:
            src = apply_edition(fh.read())
            src = re.sub(r"<!--code\s+(.*?)-->", code_excerpt, src, flags=re.S)
        m = re.match(r"\s*<!--\s*(\{.*?\})\s*-->\n", src, re.S)
        if not m:
            sys.exit(f"site/pages/{fn}: missing the settings comment on the first line")
        meta = json.loads(m.group(1))
        body, _, page_scripts = src[m.end():].partition("<!-- scripts -->")
        nav = "\n".join(
            f'      <a href="{href}"' + (' aria-current="page"' if href == fn else "") + f">{label}</a>"
            for href, label in NAV) + f'\n      <a href="{REPO_URL}">GitHub</a>'
        head, libs = [], [f'<script src="assets/edition.js?v={version}"></script>',
                          f'<script src="assets/charts.js?v={version}"></script>']
        if meta.get("math"):
            head.append('<link rel="stylesheet" href="assets/vendor/katex/katex.min.css">')
            libs.insert(0, '<script src="assets/vendor/katex/auto-render.min.js"></script>')
            libs.insert(0, '<script src="assets/vendor/katex/katex.min.js"></script>')
        if meta.get("data"):
            libs.append(f'<script src="assets/data.js?v={version}"></script>')
        for sc in meta.get("scripts", []):
            libs.append(f'<script src="{sc}?v={version}"></script>')
        title = meta["title"]
        full_title = title if fn == "index.html" else f"{title} · Phase Equilibrium Calculator"
        out = (layout.replace("{{title}}", full_title)
               .replace("{{description}}", meta.get("description", ""))
               .replace("{{head}}", "\n".join(head))
               .replace("{{body_class}}", meta.get("body_class", ""))
               .replace("{{math_attr}}", " data-math" if meta.get("math") else "")
               .replace("{{nav}}", nav)
               .replace("{{repo}}", REPO_URL)
               .replace("{{version}}", version)
               .replace("{{body}}", body.strip("\n"))
               .replace("{{scripts}}", "\n".join(libs) + "\n" + page_scripts.strip("\n")))
        with open(os.path.join(ROOT, "docs", fn), "w", encoding="utf-8") as fh:
            fh.write(out.rstrip("\n") + "\n")
    print(f"rendered {len(os.listdir(pages_dir))} pages into docs/ "
          f"({ED['name']} edition, asset version {version})")


if "--pages" in sys.argv:
    render_pages()
    sys.exit(0)

